  const folded = new Map(Object.entries(zh).map(([key, value]) => [key.toLowerCase(), value]));
  const textState = new WeakMap();
  const attributeState = new WeakMap();
  let locale = 'en';
  const protectedContent =
    'script,style,textarea,input,option,[contenteditable="true"],[data-no-translate],.employee-name,.staff-name,.person-name,.project-approval-employee-name,.project-approval-detail-employee-name,.performance-employee-name,.attendance-report-name,.me-emp-fullname,.drawer-user-name,.form-attachment-file-name,.project-assignee-name,.clocking-record-location,.entitlement-leave-value,.entitlement-metric-value,#entitlementStaffListContainer .entitlement-staff-card,#highlightBentoContainer .bento-card,#highlightTableContainer tbody,.web-employee-id,[class*="employee-id"],[class*="staff-id"]';

  function lookup(source) {
    if (locale === 'en') return source;
    const trimmed = source.trim();
    let translated = zh[trimmed] || folded.get(trimmed.toLowerCase());
    if (!translated && /[:：]$/.test(trimmed)) {
      const stem = trimmed.slice(0, -1).trim();
      const match = zh[stem] || folded.get(stem.toLowerCase());
      if (match) translated = match + '：';
    }
    if (!translated) {
      const count = trimmed.match(
        /^(Total Records|Total Count|Selected|Records|Headcount|Total Hours)\s*:\s*([\d.,]+)$/i,
      );
      if (count)
        translated = (zh[count[1]] || folded.get(count[1].toLowerCase())) + '：' + count[2];
      const records = trimmed.match(
        /^(\d+)\s+(Records?|Staff|Employees?|Hours?|Days?)(\s+selected)?$/i,
      );
      if (records)
        translated =
          records[1] +
          ' ' +
          (zh[records[2]] || folded.get(records[2].toLowerCase()) || records[2]) +
          (records[3] ? '已选择' : '');
      const ofRecords = trimmed.match(/^Showing (\d+)\s*(?:-|–|to)\s*(\d+) of (\d+) records$/i);
      if (ofRecords)
        translated =
          '显示第 ' + ofRecords[1] + '–' + ofRecords[2] + ' 条，共 ' + ofRecords[3] + ' 条记录';
      const countedLabel = trimmed.match(/^(.+?)\s*\(([\d.,]+)\)$/);
      if (countedLabel) {
        const label = zh[countedLabel[1]] || folded.get(countedLabel[1].toLowerCase());
        if (label) translated = label + ' (' + countedLabel[2] + ')';
      }
    }
    if (!translated) return source;
    return (
      source.slice(0, source.indexOf(trimmed)) +
      translated +
      source.slice(source.indexOf(trimmed) + trimmed.length)
    );
  }
  function translateText(node) {
    const parent = node.parentElement;
    if (!parent || parent.closest(protectedContent) || !node.nodeValue.trim()) return;
    // These labels and option captions are consumed by legacy source code as business values.
    const choiceLabel = parent.closest('label');
    if (choiceLabel && choiceLabel.querySelector('[data-other-request]')) return;
    if (parent.closest('td') && !parent.closest('[class*="status"], [class*="label"]')) return;
    if (parent.closest('dd') && !parent.closest('.profile-missing,.profile-supervisor-label'))
      return;
    const current = node.nodeValue;
    let state = textState.get(node);
    if (!state || current !== state.last) state = { source: current, last: current };
    const translated = lookup(state.source);
    if (translated !== current) node.nodeValue = translated;
    state.last = translated;
    textState.set(node, state);
  }
  function translateAttributes(element) {
    if (element.closest('[data-no-translate], [contenteditable="true"]')) return;
    let states = attributeState.get(element);
    if (!states) {
      states = {};
      attributeState.set(element, states);
    }
    ['placeholder', 'title', 'aria-label'].forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (current === null) return;
      let state = states[attribute];
      if (!state || current !== state.last) state = { source: current, last: current };
      const translated = lookup(state.source);
      if (translated !== current) element.setAttribute(attribute, translated);
      state.last = translated;
      states[attribute] = state;
    });
  }
  function translate(root) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateText(node);
    if (root.nodeType === 1) translateAttributes(root);
    root.querySelectorAll('[placeholder],[title],[aria-label]').forEach(translateAttributes);
  }
  function setLocale(value) {
    locale = value === 'zh' ? 'zh' : 'en';
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
    translate(document.body);
  }
