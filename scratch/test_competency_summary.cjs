const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const puppeteer = require('puppeteer');
const root = path.resolve(__dirname, '..');
const url = (file = 'competency-summary.html', query = '') => pathToFileURL(path.join(root, 'modules/training-competency/options', file)).href + query;

(async () => {
  const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--allow-file-access-from-files', '--no-sandbox'] });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewport({ width: 360, height: 900 });
    const click = async selector => { await page.$eval(selector, node => node.scrollIntoView({ block: 'center' })); await page.click(selector); };
    const navigate = async (selector, ready) => { await click(selector); await page.waitForSelector(ready); };
    const total = () => page.$eval('#csTotalRecords', node => node.textContent);
    const mainUrl = pathToFileURL(path.join(root, 'modules/training-competency/index.html')).href + '?scope=team&theme=dark';
    await page.goto(mainUrl, { waitUntil: 'domcontentloaded' });
    assert.equal(await page.$eval('[data-option-id="competency-summary"]', node => node.tagName), 'A', 'Competency Summary must open the report');
    await navigate('[data-option-id="competency-summary"]', '#csTable');
    assert.equal(await total(), '12');
    assert.deepEqual(await page.$$eval('#csTable th', nodes => nodes.map(node => node.textContent)), ['Competency', 'Count']);
    assert.deepEqual(await page.$$eval('#csTable .cs-count', nodes => nodes.map(node => node.textContent)), ['6', '3', '3']);
    await click('.cs-pdf-link');
    assert.equal(await page.$eval('#csModal', node => node.hidden), false);
    assert.match(await page.$eval('#csModalBody', node => node.textContent), /PDF Preview/);
    assert.match(await page.$eval('.cs-pdf-paper', node => node.textContent), /Effective Communication/);
    assert.equal(await page.$eval('main', node => node.inert), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.$eval('main', node => node.inert), false);
    await click('#csViewChart');
    assert.equal(await page.$eval('#csChartTotal', node => node.textContent), '12');
    assert.equal(await page.$$('#csChartSegments circle').then(nodes => nodes.length), 3);
    assert.equal(await page.$$eval('#csChartLegend .attendance-report-legend-row', nodes => nodes.reduce((sum, node) => sum + Number(node.dataset.count), 0)), 12);
    await click('#csBack');
    await navigate('[data-competency="effective-communication"] .cs-count', '#csTable[data-kind="levels"]');
    assert.equal(await total(), '6');
    assert.deepEqual(await page.$$eval('#csTable th', nodes => nodes.map(node => node.textContent)), ['Competency', 'Level', 'Count']);
    await click('#csViewChart');
    assert.equal(await page.$eval('#csChartTotal', node => node.textContent), '6');
    await click('#csBack');
    await navigate('tr[data-level="4"] .cs-row-link', '#csEmployeeCards');
    assert.equal(await total(), '3');
    assert.equal(await page.$$('.cs-employee-card').then(nodes => nodes.length), 3);
    assert.equal(await page.$eval('.cs-employee-id', node => node.previousElementSibling.className), 'cs-employee-name');
    assert.equal(await page.$eval('.cs-employee-id', node => node.textContent), '#EBB12');
    await click('#csViewChart');
    assert.equal(await page.$eval('#csChartTotal', node => node.textContent), '3');
    await click('#csBack');
    await navigate('.cs-employee-card[data-emp="EBB12"]', '#csEmployeeSummary');
    assert.deepEqual(await page.$$eval('#csEmployeeSummary .cs-summary-field > span', nodes => nodes.map(node => node.textContent)), ['Emp #', 'Name', 'Branch', 'Department', 'Position']);
    assert.deepEqual(await page.$$eval('#csTable th', nodes => nodes.map(node => node.textContent)), ['Competency', 'Level', 'Chge', 'Gap']);
    assert.equal(await page.$$('#csTable tbody tr[data-competency]').then(nodes => nodes.length), 3);
    assert.deepEqual(await page.$$eval('#csTable tbody tr:first-child td', nodes => nodes.map(node => node.textContent)), ['Effective Communication', '4', '+1', '0']);
    assert.equal(await page.$eval('#staffCompetencyAssess', node => node.textContent.trim()), 'Assess');
    await navigate('#staffCompetencyAssess', '#staffAssessForm');
    assert.match(page.url(), /staff-competency-assess\.html/);
    assert.equal(new URL(page.url()).searchParams.get('origin'), 'summary');
    assert.equal(await page.$eval('#staffAssessEmployee', node => node.textContent.trim()), 'Farhan Binti Rahmat');
    await navigate('#staffAssessBack', '#csEmployeeSummary');
    assert.match(page.url(), /competency-summary-employee\.html/);
    assert.equal(new URL(page.url()).searchParams.get('competency'), 'effective-communication');
    await click('#csTable tbody .cs-row-link');
    assert.deepEqual(await page.$$eval('#csEmployeeDetails th', nodes => nodes.map(node => node.textContent)), ['Emp #', 'Name', 'Company', 'Branch', 'Department', 'Job Title']);
    assert.equal(await page.$$('.cs-assessment-record').then(nodes => nodes.length), 2);
    assert.deepEqual(await page.$$eval('.cs-assessment-record:first-child th', nodes => nodes.map(node => node.textContent)), ['Assess Date', 'Level', 'Remarks', 'Assessor']);
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.getElementById('csModal').contains(document.activeElement)), true);
    await click('#csModalClose');
    await navigate('#csBack', '#csEmployeeCards');
    await navigate('#csBack', '#csTable[data-kind="levels"]');
    await navigate('#csBack', '#csTable[data-kind="summary"]');
    await click('#csFilterTrigger');
    assert.deepEqual(await page.$$eval('#csFilterForm .performance-highlight-filter-fields label', nodes => nodes.map(node => node.textContent)), ['Search Keyword', 'Company', 'Branch', 'Department', 'Job']);
    await page.type('#csKeyword', 'Farhan');
    await click('#csApplyFilter');
    assert.equal(await total(), '3');
    await page.reload({ waitUntil: 'domcontentloaded' });
    assert.equal(await total(), '3');
    await navigate('[data-competency="effective-communication"] .cs-count', '#csTable[data-kind="levels"]');
    assert.equal(await total(), '1');
    await navigate('tr[data-level="4"] .cs-row-link', '#csEmployeeCards');
    assert.equal(await total(), '1');
    assert.match(page.url(), /keyword=Farhan/);
    await navigate('.cs-employee-card', '#csEmployeeSummary');
    assert.match(page.url(), /keyword=Farhan/);
    await page.goto(url(), { waitUntil: 'domcontentloaded' });
    await click('#csFilterTrigger');
    await page.select('#csCompany', 'PeopleHCM Services');
    await page.select('#csBranch', 'Penang');
    await page.select('#csDepartment', 'Finance');
    await page.select('#csJob', 'Finance Analyst');
    await click('#csApplyFilter');
    assert.equal(await total(), '2');
    await click('#csFilterTrigger');
    await click('#csResetFilter');
    await click('#csApplyFilter');
    assert.equal(await total(), '12');
    await click('#csFilterTrigger');
    await page.type('#csKeyword', 'no-matching-staff');
    await click('#csApplyFilter');
    assert.equal(await total(), '0');
    assert.match(await page.$eval('#csTable', node => node.textContent), /No records/);
    await click('#csViewChart');
    assert.equal(await page.$$('#csChartSegments circle').then(nodes => nodes.length), 0);

    for (const theme of ['dark', 'light']) {
      for (const width of [360, 420]) {
        await page.setViewport({ width, height: 900 });
        await page.goto(url('competency-summary.html', `?theme=${theme}`), { waitUntil: 'domcontentloaded' });
        const capture = async name => {
          assert.equal(await page.$eval('.main-content', node => node.scrollWidth <= node.clientWidth + 1), true, `${name} ${theme} ${width}: no page overflow`);
          await page.screenshot({ path: path.join(__dirname, `competency-summary-${name}-${theme}-${width}.png`) });
        };
        await capture('report');
        await click('#csFilterTrigger'); await capture('filter'); await click('#csCloseFilter');
        await click('.cs-pdf-link'); await capture('pdf'); await click('#csModalClose');
        await click('#csViewChart'); await capture('chart'); await click('#csBack');
        await navigate('.cs-count', '#csTable[data-kind="levels"]'); await capture('levels');
        await navigate('tr[data-level="4"] .cs-row-link', '#csEmployeeCards'); await capture('employees');
        await navigate('.cs-employee-card', '#csEmployeeSummary'); await capture('employee');
        await click('#csTable tbody .cs-row-link'); await capture('assessment'); await click('#csModalClose');
        assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), theme);
      }
    }
    await page.goto(url('competency-summary-levels.html', '?competency=missing'), { waitUntil: 'domcontentloaded' });
    assert.equal(await total(), '0');
    await page.goto(url('competency-summary-employee.html', '?emp=missing'), { waitUntil: 'domcontentloaded' });
    assert.equal(await page.$eval('#csUnavailable', node => node.hidden), false);
    assert.deepEqual(errors, []);
    console.log('PASS: Competency Summary filters, 4-level drilldown, chart totals, PDF preview, employee cards, assessment history, keyboard dialogs, URL state and responsive themes');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
